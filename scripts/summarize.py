"""Build results/summary.csv and results/RESULTS.md from results/results.jsonl (stdlib only)."""
import csv
import json
import os
import statistics as st
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "results"
recs = [json.loads(l) for l in open(os.path.join(root, "results.jsonl"))]
by = {}
for r in recs:
    by.setdefault(r["run"].rsplit("_s", 1)[0], []).append(r)

ORDER = ["M0_rf", "M0_hgb", "M1_gru", "M1_gru_delta", "M2_cnn_k1", "M2_cnn_k1_delta", "M2_cnn_k3_delta",
         "M2_cnn_k5_delta", "R18_scratch_delta", "R18_ssl4eo_delta", "Presto_scratch", "Presto_pretrained"]
DESC = {
    "M0_rf": "Hand-crafted time-series stats (150) + Random Forest",
    "M0_hgb": "Hand-crafted time-series stats (150) + Gradient Boosting",
    "M1_gru": "BiGRU on patch-mean series (72x10)",
    "M1_gru_delta": "BiGRU + difference-from-first-year inputs",
    "M2_cnn_k1": "Frame CNN (32x32) + temporal Transformer",
    "M2_cnn_k1_delta": "M2 + difference-from-first-year inputs",
    "M2_cnn_k3_delta": "M2 with 3x3-patch context window (96x96 px)",
    "M2_cnn_k5_delta": "M2 with 5x5-patch context window (160x160 px)",
    "R18_scratch_delta": "ResNet18 frame encoder, random init",
    "R18_ssl4eo_delta": "ResNet18 frame encoder, SSL4EO-S12 MoCo pretrained",
    "Presto_scratch": "Presto architecture, random init",
    "Presto_pretrained": "Presto (pretrained S1/S2 pixel-time-series FM), fine-tuned",
}


def m(x):
    return st.mean(x) if x else float("nan")


def sd(x):
    return st.stdev(x) if len(x) > 1 else float("nan")


rows = []
for name in sorted(by, key=lambda n: ORDER.index(n) if n in ORDER else 99):
    rs = by[name]
    t = [r["test"] for r in rs]
    row = {"model": name, "description": DESC.get(name, ""), "seeds": len(rs),
           "val_f1": m([r["val"]["macro_f1"] for r in rs]),
           "test_f1": m([x["macro_f1"] for x in t]), "test_f1_sd": sd([x["macro_f1"] for x in t]),
           "ci_lo": m([x["f1_ci_lo"] for x in t]), "ci_hi": m([x["f1_ci_hi"] for x in t]),
           "acc": m([x["acc"] for x in t]),
           "f1_interior": m([x.get("f1_interior", float("nan")) for x in t]),
           "f1_boundary": m([x.get("f1_boundary", float("nan")) for x in t]),
           "f1_stable": m([x["f1_stable"] for x in t]), "f1_seasonal": m([x["f1_seasonal"] for x in t]),
           "f1_urban": m([x["f1_urban"] for x in t])}
    rows.append(row)

with open(os.path.join(root, "summary.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)


def fmt(v, d=3):
    return "–" if v != v else f"{v:.{d}f}"


lines = ["| Model | What it is | Seeds | Test macro-F1 | 95% CI (seed 0 bootstrap avg) | Interior F1 | Boundary F1 | F1 stable / seasonal / urban |",
         "|---|---|---|---|---|---|---|---|"]
for r in rows:
    f1 = fmt(r["test_f1"]) + ("" if r["seeds"] < 2 else f" ± {fmt(r['test_f1_sd'])}")
    lines.append(f"| `{r['model']}` | {r['description']} | {r['seeds']} | **{f1}** | [{fmt(r['ci_lo'])}, {fmt(r['ci_hi'])}] | "
                 f"{fmt(r['f1_interior'])} | {fmt(r['f1_boundary'])} | {fmt(r['f1_stable'])} / {fmt(r['f1_seasonal'])} / {fmt(r['f1_urban'])} |")
n_int = recs[0]["test"].get("n_interior")
n_bd = recs[0]["test"].get("n_boundary")
md = ["# Results (auto-generated by `scripts/summarize.py`)", "",
      "All scores are on the **weak-label** test split (spatial blocks, see README). "
      f"Interior = all 8 neighbours share the label (n={n_int}); boundary = at least half of the neighbours differ (n={n_bd}).", "",
      *lines, "", "## Confusion matrices (seed 0, rows = true, cols = pred; order stable, seasonal, urban)", ""]
for r in recs:
    if r["run"].endswith("_s0"):
        md.append(f"- `{r['run']}`: {r['test']['confusion']}")
open(os.path.join(root, "RESULTS.md"), "w").write("\n".join(md) + "\n")
print("\n".join(lines))
